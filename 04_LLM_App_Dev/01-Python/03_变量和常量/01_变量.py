"""
1、变量是什么

变量是指第一次赋值后还能再次赋值的量，Python 里变量由变量名、变量值两大部分组成：
变量名 = 变量值

* 变量名：可以认为拿到变量名就是拿到了变量所对应内存里的内存地址所指向的对象
* 变量值：可以就是存储在变量所对应内存里的内存地址
* 数据类型：
    * Python 是动态类型语言，这意味着变量本身是不固定数据类型，变量可以先指向 int，再指向 str，但这不是变量的数据类型变了，而是变量从指向整数对象，变成了指向字符串对象
    * 数据类型不需要在声明变量时手动写出来，解释器会根据变量值自动推断数据类型

需要注意的是：Python 里所有的数据类型都是引用类型，布尔值、整数值、浮点数值也都是对象
"""
a = 10   # 此时变量 a 里存储的是整数对象 10 的内存地址、指向整数对象 10
b = a    # 此时变量 b 里存储的也是整数对象 10 的内存地址、也指向整数对象 10
a = 20   # 此时变量 a 里存储的是整数对象 20 的内存地址、指向整数对象 20
print(a) # 20
print(b) # 10

