"""
7、变量的本质

变量其实是高级语言里才有的概念，为的就是方便我们开发者通过变量来操作内存。
汇编里没有变量的概念，就是在通过指令操作立即数、寄存器和内存。
高级语言里的变量其实就对应汇编里的内存。

因此变量的本质就是一块内存，操作变量就是在操作内存，比如：
声明一个变量的本质就是在开辟一块内存，
初始化一个变量的本质就是在第一次往这块内存里写数据，
给一个变量赋值的本质就是在修改这块内存里的数据，
读取一个变量的值的本质就是在把数据从这块内存里给读出来，
获取一个变量的地址的本质就是在获取这块内存的首地址。
"""